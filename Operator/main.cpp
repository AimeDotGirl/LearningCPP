#include <iostream>
using namespace std;

int main()
{
    cout << "1 + 1 = " << 1 + 1 << endl;
    cout << "1 - 2 = " << 1 - 2 << endl;
    cout << "14 * 3 = " << 14 * 3 << endl;
    cout << "15 / 5 = " << 15 / 5 << endl;
    cout << "5 % 3 = " << 5 % 3 << endl;

    cout << "1 + 1 - 2 + 14 * 3 + 15 / 5 + 5 % 3 = " << 1 + 1 - 2 + 14 * 3 + 15 / 5 + 5 % 3 << endl;

    return 0;
}